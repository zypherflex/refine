const DICTS: Record<Lang, Partial<Record<HubKey, string>>> = { en, pcm, ha };

export function translate(lang: Lang, key: HubKey, vars: Record<string, string | number> = {}): string {
  const raw = DICTS[lang][key] ?? en[key];
  return raw.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
}

export type T = (key: HubKey, vars?: Record<string, string | number>) => string;
export const translator = (lang: Lang): T => (key, vars) => translate(lang, key, vars);
export const langLabel = (l: Lang) => LANGS.find((x) => x.id === l)!.label;

/** Keys a language has not translated yet; they fall back to English. */
export const missingKeys = (lang: Lang) => (Object.keys(en) as HubKey[]).filter((k) => !DICTS[lang][k]);
